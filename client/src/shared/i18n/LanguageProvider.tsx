type LanguageContextValue = { language: Language; isArabic: boolean; setLanguage: (language: Language) => void; t: (text: string) => string; formatDate: (date: string | null | undefined) => string; formatNumber: (value: number) => string };
const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => localStorage.getItem("kanbot-language") === "ar" ? "ar" : "en");
  const setLanguage = (next: Language) => {
    localStorage.setItem("kanbot-language", next);
    setLanguageState(next);
  };
  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  }, [language]);
  const value = useMemo<LanguageContextValue>(() => ({
    language,
    isArabic: language === "ar",
    setLanguage,
    t: (text) => language === "ar" ? extraTranslations[text] ?? translations[text] ?? text : text,
    formatDate: (date) => {
      if (!date) return "—";
      const parsed = /^\d{4}-\d{2}-\d{2}$/.test(date) ? new Date(`${date}T12:00:00`) : new Date(date);
      return new Intl.DateTimeFormat(language === "ar" ? "ar-SY" : "en-US", { dateStyle: "medium" }).format(parsed);
    },
    formatNumber: (value) => new Intl.NumberFormat(language === "ar" ? "ar-SY" : "en-US").format(value),
  }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

// eslint-disable-next-line react-refresh/only-export-components
export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
